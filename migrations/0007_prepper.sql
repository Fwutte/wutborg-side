-- Udkastet er en klargøringsliste, ikke en optælling af beholdningen.
-- Bevar derfor antal som ukendt og alle flueben som umarkerede.
CREATE TABLE IF NOT EXISTS prepper_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  category TEXT NOT NULL CHECK (category IN ('Vand','Mad','Strøm og lys','Varme','Hygiejne','Sundhed','Praktisk')),
  name TEXT NOT NULL,
  amount REAL CHECK (amount IS NULL OR amount BETWEEN 0 AND 1000000),
  target_amount REAL CHECK (target_amount IS NULL OR target_amount BETWEEN 0 AND 1000000),
  unit TEXT NOT NULL DEFAULT '',
  check_label TEXT NOT NULL DEFAULT 'Klargjort',
  is_ready INTEGER NOT NULL DEFAULT 0 CHECK (is_ready IN (0,1)),
  notes TEXT NOT NULL DEFAULT '',
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX IF NOT EXISTS ix_prepper_sort ON prepper_items(sort_order, id);

